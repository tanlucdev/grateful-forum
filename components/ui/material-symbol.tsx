export function MaterialSymbol({
  className = "",
  fill = false,
  name,
  strokeWidth = 2.2,
}: Readonly<{ className?: string; fill?: boolean; name: string; strokeWidth?: number }>) {
  const Icon = iconMap[name];

  if (Icon) {
    return (
      <Icon
        aria-hidden="true"
        className={`inline-block shrink-0 leading-none ${className}`}
        fill={fill ? "currentColor" : "none"}
        focusable="false"
        strokeWidth={strokeWidth}
        style={{ height: "1em", width: "1em" }}
      />
    );
  }

  return (
    <span
      aria-hidden="true"
      className={`inline-block h-[1em] w-[1em] shrink-0 select-none leading-none ${className}`}
    />
  );
}
