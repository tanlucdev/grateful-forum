const millisecondsPerDay = 86_400_000;

export function getDailyReflectionQuote(date = new Date(), locale: AppLocale = "vi"): DailyReflectionQuote {
  const quotes = locale === "en" ? enDailyReflectionQuotes : dailyReflectionQuotes;
  const localDay = Date.UTC(date.getFullYear(), date.getMonth(), date.getDate());
  const index = Math.floor(localDay / millisecondsPerDay) % quotes.length;

  return quotes[index];
}
